// Pure rule-engine regressions: no browser, services or production writes.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../lib/alerts.ts',import.meta.url),'utf8');
const compiled = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const exported = {};
vm.runInNewContext(compiled,{exports:exported,Intl,Date,Number,Map,Set,JSON});
const {evaluateRules,emptyAlerts,restoreAlerts,addEvents}=exported;
const start=Date.now();
const quote=(premium,time=start)=>({timestamp:new Date(time).toISOString(),premium_percentage:premium,domestic_gold_price:170000});
const rule={id:'test',metric:'premium',operator:'gte',threshold:2,enabled:true,matched:false,lastFiredAt:null};
let state={...emptyAlerts(),rules:[rule]};
state=evaluateRules(state,quote(1),start);assert.equal(state.events.length,0);
state=evaluateRules(state,quote(2),start);assert.equal(state.events.length,1);
state=evaluateRules(state,quote(3),start+1000);assert.equal(state.events.length,1);
state=evaluateRules(state,null,start+2000);assert.equal(state.rules[0].matched,true);
state=evaluateRules(state,quote(0,start-100000),start);assert.equal(state.rules[0].matched,true);
state=evaluateRules(state,quote(0),start+3000);assert.equal(state.rules[0].matched,false);
state=evaluateRules(state,quote(2),start+4000);assert.equal(state.events.length,1);
state=evaluateRules(state,quote(0,start+601000),start+601000);
state=evaluateRules(state,quote(2,start+602000),start+602000);assert.equal(state.events.length,2);
assert.equal(evaluateRules(state,quote(3,start+800000),start),state,'Future timestamps must not fire');
let zero={...emptyAlerts(),rules:[{...rule,operator:'lte',threshold:0}]};
zero=evaluateRules(zero,quote(0),start);assert.equal(zero.events.length,1);
const disabled={...emptyAlerts(),rules:[{...rule,enabled:false}]};
assert.equal(evaluateRules(disabled,quote(3),start),disabled);
assert.equal(restoreAlerts('{invalid').rules.length,0);
assert.equal(restoreAlerts(JSON.stringify(state)).events.length,2);
assert.equal(addEvents(state,state.events),state,'Repeated delivery must not duplicate inbox events');
let bounded=addEvents(emptyAlerts(),Array.from({length:120},(_,i)=>({id:String(i),kind:'system',severity:'warning',occurred_at:new Date(start+i).toISOString(),message:'test'})));
assert.equal(bounded.events.length,100);
console.log('PASS: inclusive/zero thresholds, entry detection, cooldown, stale/future isolation, recovery, persistence and deduplication');
